# Generate standards/elixir/README.md: a lightweight index of every rule, grouped by topic
# doc and section (names only, no bodies). This is the progressive-disclosure map: read it
# first to find the right topic doc, then open only that file. Regenerate with `make index`.
Code.require_file("lib/standards.ex", __DIR__)

index_path = "standards/elixir/README.md"

header = """
# Elixir Standards

How we write Elixir at Euna Payments. The topic docs live in [`topics/`](topics/); each rule is
distilled from real PR review comments by our reviewers. This page is a generated index of every
rule, grouped by topic and section (names only, no rule text), so you can find the right file
without reading them all. Read this index first, then open only the topic doc you need.

Generated by `make index` from the topic docs. Do not edit by hand.
"""

section_groups = fn rules ->
  rules
  |> Enum.chunk_by(& &1.section)
  |> Enum.map(fn group -> {hd(group).section, Enum.map(group, & &1.name)} end)
end

blocks =
  Standards.docs()
  |> Enum.map(fn path ->
    parsed = Standards.parse_doc(path)
    rel = "topics/#{Path.basename(path)}"
    title = parsed.title || Path.basename(path, ".md")

    sections =
      parsed.rules
      |> section_groups.()
      |> Enum.map_join("\n", fn {section, names} ->
        "- **#{section}:** #{Enum.join(names, ", ")}"
      end)

    "## [#{title}](#{rel})\n\n#{sections}\n"
  end)
  |> Enum.join("\n")

File.write!(index_path, header <> "\n" <> blocks)

count = Standards.docs() |> Enum.map(&Standards.parse_doc/1) |> Enum.map(&length(&1.rules)) |> Enum.sum()
IO.puts("index: #{index_path} <- #{length(Standards.docs())} docs, #{count} rules")
